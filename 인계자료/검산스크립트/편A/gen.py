def mat_switches():
    nb = len(R['bins']); sw = [0] * nb; prev = None
    for r in rows:
        k = len(r['cuts']); dur = r['en'] - r['st']
        for j, c in enumerate(r['cuts']):
            cs = r['st'] + j * dur / k
            if prev is not None and c['mat'] != prev:
                sw[min(int(cs // 30), nb - 1)] += 1
            prev = c['mat']
    return sw
